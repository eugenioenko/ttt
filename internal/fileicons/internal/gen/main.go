// Command gen regenerates icons_gen.go from a checkout of nvim-web-devicons
// (https://github.com/nvim-tree/nvim-web-devicons, MIT).
//
//	git clone --depth 1 https://github.com/nvim-tree/nvim-web-devicons /tmp/nvim-web-devicons
//	NVIM_WEB_DEVICONS=/tmp/nvim-web-devicons go generate ./internal/fileicons
//
// The upstream tables carry hex colors. ttt never hardcodes colors, so each
// hex color is reduced here to a hue family, which the explorer resolves
// through the active theme's file icon palette at render time.
package main

import (
	"bytes"
	"flag"
	"fmt"
	"go/format"
	"log"
	"math"
	"os"
	"os/exec"
	"path/filepath"
	"sort"
	"strconv"
	"strings"

	lua "github.com/yuin/gopher-lua"
)

const (
	extensionTable = "lua/nvim-web-devicons/default/icons_by_file_extension.lua"
	filenameTable  = "lua/nvim-web-devicons/default/icons_by_filename.lua"

	// Colors below this HSL saturation read as grey and inherit the row style.
	minSaturation = 0.18
)

type entry struct {
	glyph string
	color string
}

func main() {
	src := flag.String("src", os.Getenv("NVIM_WEB_DEVICONS"), "path to an nvim-web-devicons checkout (default $NVIM_WEB_DEVICONS)")
	out := flag.String("out", "icons_gen.go", "output file")
	flag.Parse()
	if *src == "" {
		log.Fatal("missing -src: clone https://github.com/nvim-tree/nvim-web-devicons and pass its path, or set NVIM_WEB_DEVICONS")
	}

	byExtension := loadTable(filepath.Join(*src, extensionTable))
	byFilename := loadTable(filepath.Join(*src, filenameTable))

	var buf bytes.Buffer
	fmt.Fprintf(&buf, "// Code generated by internal/fileicons/internal/gen from nvim-web-devicons %s. DO NOT EDIT.\n", revision(*src))
	buf.WriteString("//\n// Glyphs: nvim-web-devicons, Copyright (c) 2023 nvim-tree, MIT License.\n\n")
	buf.WriteString("package fileicons\n\n")
	writeMap(&buf, "byFilename", byFilename)
	writeMap(&buf, "byExtension", byExtension)

	formatted, err := format.Source(buf.Bytes())
	if err != nil {
		log.Fatalf("format generated source: %v", err)
	}
	if err := os.WriteFile(*out, formatted, 0o644); err != nil {
		log.Fatal(err)
	}
}

// loadTable keys entries by lowercased name because lookups lowercase first;
// when two keys differ only by case, the lowercase spelling wins.
func loadTable(path string) map[string]entry {
	L := lua.NewState()
	defer L.Close()
	if err := L.DoFile(path); err != nil {
		log.Fatalf("load %s: %v", path, err)
	}
	table, ok := L.Get(-1).(*lua.LTable)
	if !ok {
		log.Fatalf("%s did not return a table", path)
	}
	result := make(map[string]entry)
	table.ForEach(func(key, value lua.LValue) {
		row, ok := value.(*lua.LTable)
		if !ok {
			return
		}
		name := key.String()
		lower := strings.ToLower(name)
		if _, exists := result[lower]; exists && name != lower {
			return
		}
		result[lower] = entry{
			glyph: row.RawGetString("icon").String(),
			color: row.RawGetString("color").String(),
		}
	})
	return result
}

func writeMap(buf *bytes.Buffer, name string, table map[string]entry) {
	keys := make([]string, 0, len(table))
	for key := range table {
		keys = append(keys, key)
	}
	sort.Strings(keys)
	fmt.Fprintf(buf, "var %s = map[string]Icon{\n", name)
	for _, key := range keys {
		e := table[key]
		fmt.Fprintf(buf, "\t%s: {Glyph: %s, Color: %s},\n", strconv.Quote(key), strconv.QuoteToASCII(e.glyph), hueFamily(e.color))
	}
	buf.WriteString("}\n\n")
}

func hueFamily(hex string) string {
	value, err := strconv.ParseUint(strings.TrimPrefix(hex, "#"), 16, 32)
	if err != nil || len(strings.TrimPrefix(hex, "#")) != 6 {
		return "ColorDefault"
	}
	r := float64(value>>16&0xff) / 255
	g := float64(value>>8&0xff) / 255
	b := float64(value&0xff) / 255
	hue, saturation := hueSaturation(r, g, b)
	if saturation < minSaturation {
		return "ColorDefault"
	}
	switch {
	case hue < 20 || hue >= 340:
		return "ColorRed"
	case hue < 70:
		return "ColorYellow"
	case hue < 165:
		return "ColorGreen"
	case hue < 200:
		return "ColorCyan"
	case hue < 260:
		return "ColorBlue"
	default:
		return "ColorMagenta"
	}
}

func hueSaturation(r, g, b float64) (float64, float64) {
	maxC := math.Max(r, math.Max(g, b))
	minC := math.Min(r, math.Min(g, b))
	delta := maxC - minC
	if delta == 0 {
		return 0, 0
	}
	lightness := (maxC + minC) / 2
	saturation := delta / (1 - math.Abs(2*lightness-1))
	var hue float64
	switch maxC {
	case r:
		hue = math.Mod((g-b)/delta, 6)
	case g:
		hue = (b-r)/delta + 2
	default:
		hue = (r-g)/delta + 4
	}
	hue *= 60
	if hue < 0 {
		hue += 360
	}
	return hue, saturation
}

func revision(src string) string {
	out, err := exec.Command("git", "-C", src, "rev-parse", "--short=12", "HEAD").Output()
	if err != nil {
		return "(unknown revision)"
	}
	return strings.TrimSpace(string(out))
}

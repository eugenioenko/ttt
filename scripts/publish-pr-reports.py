import io
import json
import os
import subprocess
import zipfile
import zlib
from pathlib import Path
from urllib.parse import urlencode


REPORTS = (
    ("editor-bench", "<!-- ttt-editor-benchmarks -->"),
    ("size-report", "<!-- ttt-binary-size -->"),
)
MAX_REPORT_BYTES = 60000


def api(path, *args):
    return json.loads(subprocess.check_output(["gh", "api", path, *args]))


def pages(path, key=None):
    result = api(path, "--paginate", "--slurp")
    return [item for page in result for item in (page[key] if key else page)]


def read_report(repo, artifact, filename, marker):
    if artifact["size_in_bytes"] > MAX_REPORT_BYTES * 2:
        raise ValueError("Report archive is too large")
    data = subprocess.check_output([
        "gh", "api", f"repos/{repo}/actions/artifacts/{artifact['id']}/zip"
    ])
    # PR-controlled archives are read in memory, never extracted or executed.
    with zipfile.ZipFile(io.BytesIO(data)) as archive:
        entries = archive.infolist()
        if len(entries) != 1 or entries[0].filename != filename:
            raise ValueError("Unexpected report archive entries")
        if entries[0].compress_type not in (zipfile.ZIP_STORED, zipfile.ZIP_DEFLATED):
            raise ValueError("Unsupported report compression")
        if entries[0].file_size > MAX_REPORT_BYTES:
            raise ValueError("Report is too large")
        body = archive.read(entries[0]).decode("utf-8")
    if not body.startswith(marker + "\n"):
        raise ValueError("Missing report marker")
    return body


def matching_head(pr, run):
    head = pr["head"]
    return (
        pr["state"] == "open"
        and pr["base"]["ref"] == "main"
        and head["sha"] == run["head_sha"]
        and head["ref"] == run["head_branch"]
        and (head.get("repo") or {}).get("full_name")
        == run["head_repository"]["full_name"]
    )


def publish(repo, run):
    if run["event"] != "pull_request" or run["conclusion"] in ("action_required", "cancelled"):
        return
    head_repo = run.get("head_repository") or {}
    owner = head_repo.get("owner", {}).get("login")
    if not owner:
        return
    prefix = f"repos/{repo}"
    current_run = api(f"{prefix}/actions/runs/{run['id']}")
    if current_run["run_attempt"] != run["run_attempt"]:
        return

    # Fork runs can have no pull_requests entries. GitHub's PR records, never
    # artifact contents, determine which PR this run is allowed to comment on.
    query = urlencode({
        "state": "open", "base": "main",
        "head": f"{owner}:{run['head_branch']}", "per_page": 100,
    })
    prs = pages(f"{prefix}/pulls?{query}")
    pr = next((pr for pr in prs if matching_head(pr, run)), None)
    if pr is None:
        return

    artifacts = pages(f"{prefix}/actions/runs/{run['id']}/artifacts?per_page=100", "artifacts")
    for name, marker in REPORTS:
        matches = [artifact for artifact in artifacts if not artifact["expired"]
                   and artifact["name"] == f"{name}-{run['run_attempt']}"]
        if not matches:
            continue
        try:
            if len(matches) != 1:
                raise ValueError("Ambiguous report artifacts")
            body = read_report(repo, matches[0], f"{name}.md", marker)
        except (ValueError, zipfile.BadZipFile, RuntimeError, zlib.error):
            print(f"::warning::Rejected invalid {name} artifact; continuing with other reports.")
            continue
        body += (f"\n\n_Report generated by PR code at `{run['head_sha'][:12]}`. "
                 f"[CI run](https://github.com/{repo}/actions/runs/{run['id']})._\n")
        number = pr["number"]
        comments = pages(f"{prefix}/issues/{number}/comments?per_page=100")
        comment = next((comment for comment in comments
                        if comment["user"]["login"] == "github-actions[bot]"
                        and (comment.get("body") or "").startswith(marker)), None)
        endpoint = (f"{prefix}/issues/comments/{comment['id']}" if comment
                    else f"{prefix}/issues/{number}/comments")
        if not matching_head(api(f"{prefix}/pulls/{number}"), run):
            return
        # JSON on stdin keeps all report text out of shell commands and paths.
        subprocess.run(
            ["gh", "api", endpoint, "--method", "PATCH" if comment else "POST", "--input", "-"],
            input=json.dumps({"body": body}).encode(), check=True, stdout=subprocess.DEVNULL,
        )


if __name__ == "__main__":
    event = json.loads(Path(os.environ["GITHUB_EVENT_PATH"]).read_text())
    publish(os.environ["GITHUB_REPOSITORY"], event["workflow_run"])
